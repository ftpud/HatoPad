const idPattern = /^[A-Za-z0-9_-]{1,200}$/;
const releasePattern = "[0-9a-f]{40,64}-node[0-9]+(-repair-[a-zA-Z0-9]+|-bundle-[a-zA-Z0-9-]+)?";
function shell(value: string): string {
  return `'${value.replaceAll("'", `'"'"'`)}'`;
}

export type AutostartTarget =
  | { kind: "ssh"; workspaceId: string; workspace: string; port: number }
  | { kind: "local"; workspaceId: string; workspace: string; port: number; userData: string; node: string };

function validate(target: AutostartTarget): void {
  if (
    !idPattern.test(target.workspaceId) ||
    !Number.isInteger(target.port) ||
    target.port < 1 ||
    target.port > 65535 ||
    !target.workspace ||
    /[\u0000-\u001f]/.test(target.workspace)
  )
    throw new Error("Invalid autostart parameters");
  if (
    target.kind === "local" &&
    (!target.userData.startsWith("/") ||
      /[\u0000-\u001f]/.test(target.userData) ||
      !target.node.startsWith("/") ||
      /[\u0000-\u001f]/.test(target.node))
  )
    throw new Error("Invalid autostart parameters");
}

/**
 * Boot script. It resolves the *currently selected* release every time, so a Core updated through Hub
 * starts on that release after a reboot; it only starts supervised releases (a bare Core cannot update itself).
 */
export function autostartScript(target: AutostartTarget): string {
  validate(target);
  const local = target.kind === "local";
  const releases = local ? `${shell(`${target.userData}/core-releases`)}` : '"$HOME/.hatopad-deploy/releases"';
  const root = local ? shell(`${target.userData}/core-releases`) : '"$HOME/.hatopad-deploy"';
  const selection = local
    ? shell(`${target.userData}/core-releases/selected-${target.workspaceId}`)
    : `"$HOME/.hatopad-server-${target.workspaceId}.release"`;
  const pairing = local
    ? shell(`${target.userData}/cloud-pairings/${target.workspaceId}.json`)
    : `"$HOME/.hatopad/cloud-pairings/${target.workspaceId}.json"`;
  const log = local
    ? shell(`${target.userData}/logs/local-core-${target.workspaceId}.log`)
    : `"$HOME/.hatopad-server-${target.workspaceId}.log"`;
  const token = local
    ? shell(`${target.userData}/core-tokens/${target.workspaceId}.token`)
    : `"$HOME/.hatopad-server-${target.workspaceId}.token"`;
  const lines = [
    "#!/bin/bash",
    "# Generated by HatoPad Gateway: starts this workspace's Core under the release supervisor at boot/login.",
    "set -eu",
    "umask 077",
    'export PATH="$HOME/.local/bin:$HOME/.volta/bin:$PATH:/usr/local/bin:/opt/homebrew/bin"',
    `releases=${releases}`,
    `selection=${selection}`,
    `release=$(cat "$selection" 2>/dev/null || true)`,
    `[[ "$release" =~ ^${releasePattern}$ ]] || { echo 'No selected Core release; start the Core from Gateway first' >&2; exit 1; }`,
    'release_directory="$releases/$release"',
    '[ -f "$release_directory/scripts/core-release-service.mjs" ] || { echo "Release $release is not supervised; update the Core first" >&2; exit 1; }',
    'cd "$release_directory"',
    'node_binary=node; if [ -x "$PWD/bin/node" ]; then node_binary="$PWD/bin/node"; export PATH="$PWD/bin:$PATH"; fi',
    ...(local ? [`[ "$node_binary" != node ] || node_binary=${shell(target.node)}`] : []),
    `pairing=${pairing}`,
    'hub_flag=""; if [ -f "$pairing" ]; then hub_flag="--hub-connect"; fi',
    `logfile=${log}`,
    'mkdir -p "$(dirname "$logfile")"',
    `export HATOPAD_CORE_RELEASE_ROOT=${root} HATOPAD_CORE_RELEASE_SELECTION="$selection" HATOPAD_HUB_PAIRING_FILE="$pairing"`,
  ];
  if (local) {
    lines.push('[ "${1:-}" != "--check" ] || exit 0');
    lines.push(
      `export HATOPAD_CORE_RELEASES_DIR=${releases} HATOPAD_SESSION_TOKEN= HATOPAD_SESSION_TOKEN_FILE=${token}`,
    );
    lines.push(
      `exec "$node_binary" scripts/core-release-service.mjs $hub_flag --host 127.0.0.1 --port ${target.port} --workspace ${shell(target.workspace)} >> "$logfile" 2>&1 < /dev/null`,
    );
  } else {
    lines.push(
      `tokenfile=${token}`,
      'test ! -L "$tokenfile" && SESSION_TOKEN=$(cat "$tokenfile")',
      '[[ "$SESSION_TOKEN" =~ ^[A-Za-z0-9_-]+$ ]] && [ "${#SESSION_TOKEN}" -ge 32 ] && [ "${#SESSION_TOKEN}" -le 256 ] || { echo "Invalid Core session token file" >&2; exit 1; }',
      '[ "${1:-}" != "--check" ] || exit 0',
      `echo $$ > "$HOME/.hatopad-server-${target.workspaceId}.pid"`,
      `HATOPAD_SESSION_TOKEN="$SESSION_TOKEN" exec "$node_binary" scripts/core-release-service.mjs $hub_flag --host 127.0.0.1 --port ${target.port} --gateway-workspace-id ${target.workspaceId} --workspace ${shell(target.workspace)} >> "$logfile" 2>&1 < /dev/null`,
    );
  }
  return lines.join("\n") + "\n";
}

const names = (id: string) => ({
  service: `hatopad-core-${id}.service`,
  label: `dev.hatopad.core.${id}`,
  script: `$HOME/.hatopad-deploy/autostart-${id}.sh`,
  marker: `hatopad-autostart-${id}`,
});
const linuxBus = 'export XDG_RUNTIME_DIR="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"';

export function autostartInstallCommand(target: AutostartTarget): string {
  const script = autostartScript(target);
  const { service, label, script: path, marker } = names(target.workspaceId);
  return `set -eu
umask 077
script="${path}"
mkdir -p "$(dirname "$script")"
printf '%s' ${shell(Buffer.from(script).toString("base64"))} | base64 -d > "$script.tmp"
chmod 700 "$script.tmp"
"$script.tmp" --check || { rm -f "$script.tmp"; echo 'Start on boot needs a Core that has been updated to a managed release.' >&2; exit 1; }
mv "$script.tmp" "$script"
case "$(uname -s)" in
Linux)
  ${linuxBus}
  if command -v systemctl >/dev/null 2>&1 && systemctl --user show-environment >/dev/null 2>&1; then
    directory="$HOME/.config/systemd/user"
    mkdir -p "$directory"
    cat > "$directory/${service}.tmp" <<'UNIT'
[Unit]
Description=HatoPad Core (${target.workspaceId})
After=network-online.target

[Service]
Type=simple
ExecStart=/bin/bash %h/.hatopad-deploy/autostart-${target.workspaceId}.sh

[Install]
WantedBy=default.target
UNIT
    mv "$directory/${service}.tmp" "$directory/${service}"
    systemctl --user daemon-reload
    systemctl --user enable ${service} >/dev/null 2>&1
    if loginctl enable-linger "$(id -un)" >/dev/null 2>&1; then echo HATOPAD_AUTOSTART:on:systemd-boot; else echo HATOPAD_AUTOSTART:on:systemd-login; fi
  elif command -v crontab >/dev/null 2>&1; then
    (crontab -l 2>/dev/null | grep -v ${shell(marker)} || true; printf '%s\\n' "@reboot /bin/bash $script # ${marker}") | crontab -
    echo HATOPAD_AUTOSTART:on:cron-boot
  else
    echo 'Neither systemd user services nor cron are available on this host' >&2; exit 1
  fi ;;
Darwin)
  directory="$HOME/Library/LaunchAgents"
  mkdir -p "$directory"
  cat > "$directory/${label}.plist.tmp" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>Label</key><string>${label}</string>
<key>ProgramArguments</key><array><string>/bin/bash</string><string>$script</string></array>
<key>RunAtLoad</key><true/>
<key>KeepAlive</key><false/>
</dict></plist>
PLIST
  mv "$directory/${label}.plist.tmp" "$directory/${label}.plist"
  echo HATOPAD_AUTOSTART:on:launchd-login ;;
*) echo 'Start on boot is available on Linux and macOS only' >&2; exit 1 ;;
esac`;
}

export function autostartRemoveCommand(workspaceId: string): string {
  if (!idPattern.test(workspaceId)) throw new Error("Invalid autostart parameters");
  const { service, label, script, marker } = names(workspaceId);
  return `set -eu
case "$(uname -s)" in
Linux)
  ${linuxBus}
  if command -v systemctl >/dev/null 2>&1 && systemctl --user show-environment >/dev/null 2>&1; then
    systemctl --user disable ${service} >/dev/null 2>&1 || true
    rm -f "$HOME/.config/systemd/user/${service}"
    systemctl --user daemon-reload >/dev/null 2>&1 || true
  fi
  if command -v crontab >/dev/null 2>&1 && crontab -l 2>/dev/null | grep -q ${shell(marker)}; then (crontab -l 2>/dev/null | grep -v ${shell(marker)} || true) | crontab -; fi ;;
Darwin)
  launchctl disable "gui/$(id -u)/${label}" >/dev/null 2>&1 || true
  rm -f "$HOME/Library/LaunchAgents/${label}.plist" ;;
esac
rm -f "${script}"
echo HATOPAD_AUTOSTART:off`;
}

export function autostartStatusCommand(workspaceId: string): string {
  if (!idPattern.test(workspaceId)) throw new Error("Invalid autostart parameters");
  const { service, label, marker } = names(workspaceId);
  return `case "$(uname -s)" in
Linux)
  ${linuxBus}
  if [ -f "$HOME/.config/systemd/user/${service}" ] && systemctl --user is-enabled ${service} >/dev/null 2>&1; then echo HATOPAD_AUTOSTART:on
  elif command -v crontab >/dev/null 2>&1 && crontab -l 2>/dev/null | grep -q ${shell(marker)}; then echo HATOPAD_AUTOSTART:on
  elif command -v systemctl >/dev/null 2>&1 || command -v crontab >/dev/null 2>&1; then echo HATOPAD_AUTOSTART:off
  else echo HATOPAD_AUTOSTART:unsupported; fi ;;
Darwin) if [ -f "$HOME/Library/LaunchAgents/${label}.plist" ]; then echo HATOPAD_AUTOSTART:on; else echo HATOPAD_AUTOSTART:off; fi ;;
*) echo HATOPAD_AUTOSTART:unsupported ;;
esac`;
}

export type AutostartState = { state: "on" | "off" | "unsupported"; mode?: string };
export function parseAutostart(output: string): AutostartState {
  const line = output.split(/\r?\n/).find((item) => item.startsWith("HATOPAD_AUTOSTART:"));
  const [, state, mode] = line?.trim().split(":") ?? [];
  if (state !== "on" && state !== "off" && state !== "unsupported")
    throw new Error("Could not read the start-on-boot state");
  return { state, ...(mode && /^[a-z-]+$/.test(mode) ? { mode } : {}) };
}
/** Explains what a mode really guarantees, so "on" is never overstated. */
export function autostartExplanation(mode?: string): string {
  switch (mode) {
    case "systemd-boot":
      return "Starts at boot (systemd user service with lingering).";
    case "systemd-login":
      return "Starts when this user logs in. Lingering could not be enabled, so a reboot with nobody logged in will not start it; ask an administrator to run: loginctl enable-linger <user>.";
    case "cron-boot":
      return "Starts at boot through cron @reboot.";
    case "launchd-login":
      return "Starts when this user logs in to macOS (launch agent).";
    default:
      return "Starts automatically.";
  }
}
