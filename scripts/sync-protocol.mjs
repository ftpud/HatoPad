import { readFile, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const versions = JSON.parse(await readFile(new URL("protocol-versions.json", root), "utf8"));
if (
  ![versions.server, versions.client.minimum, versions.client.maximum].every((v) => Number.isSafeInteger(v) && v > 0) ||
  versions.client.minimum > versions.client.maximum
)
  throw Error("Invalid protocol versions");
const helper = await readFile(new URL("packages/protocol/src/core-releases.ts", root), "utf8");
const text = `// Generated by scripts/sync-protocol.mjs from protocol-versions.json.
export const serverProtocolVersion = ${versions.server};
export const protocolCompatibility = ${JSON.stringify(versions.client)};
`;
for (const [file, content] of [
  ["packages/protocol/src/protocol-versions.ts", text],
  ["packages/gateway/src/electron/protocol-versions.ts", text + helper],
]) {
  const url = new URL(file, root);
  if (process.argv.includes("--check")) {
    if ((await readFile(url, "utf8")) !== content) throw Error(`Run node scripts/sync-protocol.mjs: ${file} is stale`);
  } else await writeFile(url, content);
}
